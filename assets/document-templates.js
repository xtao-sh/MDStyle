  function validateCatalog() {
    const themeIds = new Set((global.MDStyleThemeCatalog?.themes || []).map(theme => theme.id));
    const targetIds = new Set(["general", "wechat", "email"]);
    const ids = new Set();
    templates.forEach(template => {
      if (!/^[a-z][a-z0-9-]*$/.test(template.id) || ids.has(template.id)) throw new Error(`Invalid or duplicate template id: ${template.id}`);
      if (!template.name || !template.cat || !template.description) throw new Error(`Template metadata is incomplete: ${template.id}`);
      if (!themeIds.has(template.styleId)) throw new Error(`Template theme is missing: ${template.id}`);
      if (!targetIds.has(template.targetId)) throw new Error(`Template target is invalid: ${template.id}`);
      if (!Array.isArray(template.tags) || !Array.isArray(template.outline) || !template.markdown.startsWith("# ")) throw new Error(`Template content is invalid: ${template.id}`);
      ids.add(template.id);
    });
  }

